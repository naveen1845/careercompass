package com.careercompass.model;

import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Embedded;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OrderColumn;
import jakarta.persistence.Table;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * Entity representing a completed assessment evaluation.
 * Encapsulates:
 * - Student identification details
 * - Submission timestamp
 * - Submitted raw answers (15 responses)
 * - Calculated normalized scores across all five dimensions
 * - Top ranked career recommendations generated by the rule-based engine.
 */
@Entity
@Table(name = "assessment_results")
public class AssessmentResult {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Embedded
    private Student student;

    @Column(name = "created_at", nullable = false)
    private LocalDateTime createdAt;

    @ElementCollection
    @CollectionTable(name = "assessment_answers", joinColumns = @JoinColumn(name = "assessment_id"))
    private List<Response> answers = new ArrayList<>();

    @ElementCollection
    @CollectionTable(name = "assessment_trait_scores", joinColumns = @JoinColumn(name = "assessment_id"))
    private List<TraitScore> traitScores = new ArrayList<>();

    @ElementCollection
    @CollectionTable(name = "assessment_recommendations", joinColumns = @JoinColumn(name = "assessment_id"))
    private List<CareerRecommendation> recommendations = new ArrayList<>();

    public AssessmentResult() {
        this.createdAt = LocalDateTime.now();
    }

    public AssessmentResult(Student student, List<Response> answers,
                            List<TraitScore> traitScores,
                            List<CareerRecommendation> recommendations) {
        this.student = student;
        this.answers = (answers != null) ? new ArrayList<>(answers) : new ArrayList<>();
        this.traitScores = (traitScores != null) ? new ArrayList<>(traitScores) : new ArrayList<>();
        this.recommendations = (recommendations != null) ? new ArrayList<>(recommendations) : new ArrayList<>();
        this.createdAt = LocalDateTime.now();
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Student getStudent() {
        return student;
    }

    public void setStudent(Student student) {
        this.student = student;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public List<Response> getAnswers() {
        return answers;
    }

    public void setAnswers(List<Response> answers) {
        this.answers = (answers != null) ? new ArrayList<>(answers) : new ArrayList<>();
    }

    public List<TraitScore> getTraitScores() {
        return traitScores;
    }

    public void setTraitScores(List<TraitScore> traitScores) {
        this.traitScores = (traitScores != null) ? new ArrayList<>(traitScores) : new ArrayList<>();
    }

    public List<CareerRecommendation> getRecommendations() {
        return recommendations;
    }

    public void setRecommendations(List<CareerRecommendation> recommendations) {
        this.recommendations = (recommendations != null) ? new ArrayList<>(recommendations) : new ArrayList<>();
    }

    /**
     * Helper to retrieve a TraitScore for a specific dimension.
     */
    public TraitScore getScoreForDimension(Dimension dimension) {
        if (traitScores == null) return null;
        return traitScores.stream()
                .filter(ts -> ts.getDimension() == dimension)
                .findFirst()
                .orElse(null);
    }
}
